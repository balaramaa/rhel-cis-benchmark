def write(path, content):
    OUT[os.path.join(ROOT, path)] = content


HEADER = "---\n# GENERATED by tools/generate.py - do not edit by hand.\n"


def build_role(v):
    bench = json.load(open(os.path.join(ROOT, "tools", "benchmarks", f"rhel{v}.json")))
    c = Ctx(v)
    P = c.p
    c.ids_by_title = {r["title"]: r["id"] for r in bench["rules"]}
    role = f"rhel{v}/roles/cis_rhel{v}"
    sections = OrderedDict()
    coverage = []
    for rule in bench["rules"]:
        tasks, kind = implement(c, rule)
        if tasks is None:
            tasks, kind = c.manual(rule["id"], rule["title"]), "manual"
            print(f"  [rhel{v}] no implementation for {rule['id']} {rule['title']} -> manual", file=sys.stderr)
        block = OrderedDict()
        block["name"] = f"{rule['id']} | {rule['title']}"
        block["when"] = f"'{rule['id']}' in {P}_active_rules"
        block["tags"] = tags_for(rule)
        block["block"] = builtinize(strip_none(tasks), P)
        sections.setdefault(section_of(rule["id"]), []).append(block)
        coverage.append((rule, kind))

    # ---- section task files
    for s, blocks in sections.items():
        pre = []
        if s == "6":
            pre = audit_setup(c)
        if s == "5":
            pre = ssh_setup(c)
        body = HEADER + f"# Section {s} - {SECTION_NAMES.get(s, '')}\n" + dump(pre + blocks)
        write(f"{role}/tasks/section_{s}.yml", body)

    main = [OrderedDict([("name", "PRELIM | Gather facts and compute the active rule set"),
                         ("ansible.builtin.import_tasks", "prelim.yml"), ("tags", ["always"])])]
    for s in sections:
        main.append(OrderedDict([("name", f"SECTION {s} | {SECTION_NAMES.get(s, '')}"),
                                 ("ansible.builtin.import_tasks", f"section_{s}.yml")]))
    main.append(OrderedDict([("name", "POST | Flush handlers and write the compliance report"),
                             ("ansible.builtin.import_tasks", "post.yml"), ("tags", ["always"])]))
    write(f"{role}/tasks/main.yml", HEADER + dump(main))
    write(f"{role}/tasks/prelim.yml", HEADER + dump(prelim(c, bench)))
    write(f"{role}/tasks/post.yml", HEADER + dump(post(c)))
    write(f"{role}/handlers/main.yml", HEADER + dump(handlers(c)))
    write(f"{role}/vars/main.yml", HEADER + dump({
        f"{P}_benchmark": {"name": bench["benchmark"], "version": bench["version"], "rhel": int(v)},
        f"{P}_rules": OrderedDict((r["id"], OrderedDict([("title", r["title"]), ("type", r["type"]),
                                                         ("server", r["server"]),
                                                         ("workstation", r["workstation"])]))
                                  for r in bench["rules"]),
        f"{P}_audit_watch_candidates": AUDIT_WATCH_PATHS,
    }))
    write(f"{role}/defaults/main.yml", defaults(c, bench))
    write(f"{role}/meta/main.yml", HEADER + dump({
        "galaxy_info": {"role_name": f"cis_rhel{v}", "author": "YOUR_NAME",
                        "description": f"Apply the {bench['benchmark']} {bench['version']} to RHEL {v} and compatible systems",
                        "license": "MIT", "min_ansible_version": "2.14",
                        "platforms": [{"name": "EL", "versions": [v]}],
                        "galaxy_tags": ["cis", "security", "hardening", "compliance", f"rhel{v}"]},
        "dependencies": []}))
    write(f"{role}/templates/rsyslog-remote.conf.j2", RSYSLOG_TMPL.replace("P_", P + "_"))
    write(f"{role}/README.md", role_readme(c, bench, coverage))
    write(f"rhel{v}/CONTROLS.md", controls_doc(c, bench, coverage))
    _write_bundle(c, bench, coverage, write)
    return bench, coverage


