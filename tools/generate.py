# --------------------------------------------------------------------------- YAML
class Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _str(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    if "'" in data and '"' not in data and "\\" not in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style='"')
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


Dumper.add_representer(str, _str)
Dumper.add_representer(OrderedDict, lambda d, x: d.represent_dict(x.items()))


def dump(obj):
    return yaml.dump(obj, Dumper=Dumper, sort_keys=False, width=1000, allow_unicode=True,
                     default_flow_style=False)


def strip_none(o):
    if isinstance(o, dict):
        return {k: strip_none(v) for k, v in o.items() if v is not None}
    if isinstance(o, list):
        return [strip_none(x) for x in o]
    return o


