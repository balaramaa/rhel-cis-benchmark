# --------------------------------------------------------------------------- docs
def stats(coverage):
    out = {"remediate": 0, "audit": 0, "manual": 0}
    for _, k in coverage:
        out[k] += 1
    return out


def lvl(x):
    return f"L{x}" if x else "-"


def controls_doc(c, bench, coverage):
    s = stats(coverage)
    lines = [f"# RHEL {c.v} - {bench['benchmark']} {bench['version']}", "",
             "_Generated by `tools/generate.py`._", "",
             f"Total controls: **{len(coverage)}** - remediated: **{s['remediate']}**, "
             f"audited (report only): **{s['audit']}**, manual (evidence collected): **{s['manual']}**.", "",
             "| ID | Title | Server | Workstation | CIS type | Role behaviour | Skip with |",
             "|----|-------|--------|-------------|----------|----------------|-----------|"]
    for r, k in coverage:
        lines.append(f"| {r['id']} | {r['title']} | {lvl(r['server'])} | {lvl(r['workstation'])} | {r['type']} | {k} | "
                     f"`--skip-tags rule_{r['id']}` |")
    return "\n".join(lines) + "\n"


def role_readme(c, bench, coverage):
    s = stats(coverage)
    return f"""# cis_rhel{c.v}

Applies the **{bench['benchmark']} {bench['version']}** to RHEL {c.v} and binary-compatible rebuilds
(Rocky Linux, AlmaLinux, Oracle Linux).

* {len(coverage)} controls: {s['remediate']} remediated, {s['audit']} audited, {s['manual']} manual (evidence collected)
* Every control is a block tagged `rule_<id>`, `section_<n>`, `level<n>_server` / `level<n>_workstation`
* Every variable is prefixed `{c.p}_` - see `defaults/main.yml`
* Full control list: [`CONTROLS.md`](../../CONTROLS.md)

This role refuses to run on any other major version.
"""


# --------------------------------------------------------------------------- main
def main():
    check = "--check" in sys.argv
    summary = []
    for v in VERSIONS:
        bench, cov = build_role(v)
        summary.append((v, bench, stats(cov), len(cov)))
    rows = "\n".join(f"| RHEL {v} | {b['benchmark']} | {b['version']} | {n} | {s['remediate']} | {s['audit']} | {s['manual']} |"
                     for v, b, s, n in summary)
    write("docs/COVERAGE.md", "# Control coverage\n\n_Generated by `tools/generate.py`._\n\n"
          "| OS | Benchmark | Version | Controls | Remediated | Audited | Manual |\n|---|---|---|---|---|---|---|\n" + rows + "\n")
    stale = []
    for path, content in OUT.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != content:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as f:
                    f.write(content)
            if path.endswith(".sh"):
                os.chmod(path, 0o755)
    if check and stale:
        print("Generated files are out of date:\n  " + "\n  ".join(os.path.relpath(p, ROOT) for p in stale))
        sys.exit(1)
    for v, b, s, n in summary:
        print(f"RHEL {v}: {n} controls ({s['remediate']} remediated, {s['audit']} audited, {s['manual']} manual)")


if __name__ == "__main__":
    main()
