        {"name": f"{P} systemd daemon-reload", "ansible.builtin.systemd": {"daemon_reload": True}},
        {"name": f"{P} update crypto policy",
         "ansible.builtin.command": "update-crypto-policies --set {{ ([%s_crypto_base] + (%s_crypto_modules | unique)) | join(':') }}" % (P, P),
         "changed_when": True, "notify": f"{P} flag reboot"},
        {"name": f"{P} dconf update", "ansible.builtin.command": "dconf update", "changed_when": True},
        {"name": f"{P} restart postfix", "ansible.builtin.systemd": {"name": "postfix", "state": "restarted"}},
        {"name": f"{P} restart chronyd", "ansible.builtin.systemd": {"name": "chronyd", "state": "restarted"}},
        {"name": f"{P} restart journald", "ansible.builtin.systemd": {"name": "systemd-journald", "state": "restarted"}},
        {"name": f"{P} restart rsyslog", "ansible.builtin.systemd": {"name": "rsyslog", "state": "restarted"}},
